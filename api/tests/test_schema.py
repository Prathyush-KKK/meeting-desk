def test_a_note_is_unique_per_meeting_and_text_while_it_is_live() -> None:
    indexes = {i.name: i for i in Base.metadata.tables["notes"].indexes}
    live = indexes["uq_notes_meeting_text_live"]
    assert live.unique
    assert [c.name for c in live.columns] == ["meeting_id", "text_hash"]
    # Partial on both dialects, so a removed note does not block the same text being pasted again.
    assert "deleted_at IS NULL" in str(live.dialect_options["postgresql"]["where"])
    assert "deleted_at IS NULL" in str(live.dialect_options["sqlite"]["where"])


def test_the_migration_is_in_step_with_the_models(tmp_path: Path) -> None:
    config = Config(str(API_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(API_ROOT / "alembic"))
    config.set_main_option("sqlalchemy.url", f"sqlite:///{tmp_path / 'migration.db'}")
    command.upgrade(config, "head")
    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - only on drift
        raise AssertionError(f"alembic revision --autogenerate is needed: {exc}") from exc
    command.downgrade(config, "base")
