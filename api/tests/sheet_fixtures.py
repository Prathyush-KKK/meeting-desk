"""Loader for the shared sheet fixtures.

``tests/fixtures/sheets/*.json`` is generated by ``_generate_from_reference.mjs`` straight out of
``web/src/lib/sheet.ts``. Everything under ``expect`` is the TypeScript reference's own
output; ``with_hooks`` is hand-written and covers the Python-only formula/date behaviour.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import cache
from pathlib import Path
from typing import Any

from app.sheets.planner import PointForSheet

FIXTURE_DIR = Path(__file__).parent / "fixtures" / "sheets"

NAMES = [
    "headers_row_1",
    "headers_row_9_banner",
    "no_header",
    "two_header_rows",
    "formula_col",
    "date_col",
    "task_keyed_no_id",
]


@dataclass(slots=True)
class SheetFixture:
    raw: dict[str, Any]

    @property
    def name(self) -> str:
        return self.raw["name"]

    @property
    def title(self) -> str:
        return self.raw["title"]

    @property
    def rows(self) -> list[list[str]]:
        return [list(r) for r in self.raw["rows"]]

    @property
    def formulas(self) -> list[list[str]] | None:
        return self.raw.get("formulas")

    @property
    def number_formats(self) -> list[list[str]] | None:
        return self.raw.get("number_formats")

    @property
    def dropdowns(self) -> dict[int, list[str]]:
        return {int(k): list(v) for k, v in self.raw["dropdowns"].items()}

    @property
    def formula_cols(self) -> list[int]:
        return list(self.raw["formula_cols"])

    @property
    def date_cols(self) -> list[int]:
        return list(self.raw["date_cols"])

    @property
    def points(self) -> list[PointForSheet]:
        return [PointForSheet(**p) for p in self.raw["points"]]

    @property
    def anchor(self) -> tuple[int, int]:
        a = self.raw["fill"]["anchor"]
        return a["r"], a["c"]

    @property
    def write_keys(self) -> bool:
        return bool(self.raw["fill"]["write_keys"])

    @property
    def expect(self) -> dict[str, Any]:
        return self.raw["expect"]

    @property
    def with_hooks(self) -> dict[str, Any] | None:
        return self.raw.get("with_hooks")


@cache
def load(name: str) -> SheetFixture:
    return SheetFixture(json.loads((FIXTURE_DIR / f"{name}.json").read_text()))


def all_fixtures() -> list[SheetFixture]:
    return [load(n) for n in NAMES]
